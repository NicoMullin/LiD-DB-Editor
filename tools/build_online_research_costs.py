"""Build the Online Research Costs mod from S3er0i9ng's online recipe profile.

A maintenance tool, not something a player runs. S3er0i9ng's Mod Manager ships
online-recipe-profile.json: for 1,017 research recipes, each cost the offline
game changed, as [offline, online], read from the PS4 online game's 4.18
parameters (partresearch). This writes it as two SQL files for
mods/Online Research Costs:

    materials.sql    craft_mate*_num, lvup_mate*_num and lvup_mate*_add_num
    splithium.sql    craft_spirit and lvup_spirit

Every offline value is checked against a stock masters.db first, so a game
update that changed a recipe stops the build instead of being written over:

    py -3 tools/build_online_research_costs.py --profile PATH/TO/online-recipe-profile.json --vanilla PATH/TO/masters.db
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "mods" / "Online Research Costs"
SPLITHIUM = ("craft_spirit", "lvup_spirit")

parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
parser.add_argument("--profile", required=True, type=Path)
parser.add_argument("--vanilla", required=True, type=Path, help="a stock masters.db")
parser.add_argument("--out", type=Path, default=OUT)
args = parser.parse_args()

profile = json.loads(args.profile.read_text(encoding="utf-8"))
rows = profile["rows"]
con = sqlite3.connect(f"file:{args.vanilla.as_posix()}?mode=ro", uri=True)
columns = [c[1] for c in con.execute("PRAGMA table_info(master_part_research)")]
version = con.execute("SELECT value FROM master_const_str WHERE id = 'TITLE_VERSION'").fetchone()
problems = []
for ptid, fields in rows.items():
    found = con.execute("SELECT * FROM master_part_research WHERE ptid = ?", (ptid,)).fetchall()
    if len(found) != 1:
        problems.append(f"{ptid}: {len(found)} rows")
        continue
    current = dict(zip(columns, found[0]))
    for field, (offline, _online) in fields.items():
        if field not in columns:
            problems.append(f"{ptid}.{field}: no such column")
        elif current[field] != offline:
            problems.append(f"{ptid}.{field}: {current[field]} here, {offline} in the profile")
con.close()
if problems:
    sys.exit(f"{len(problems)} recipe(s) differ from the profile's offline values: " + "; ".join(problems[:8]))


def number(value) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def write(name: str, keep, heading: list[str]) -> int:
    lines = [f"-- {line}" if line else "--" for line in heading] + [""]
    count = 0
    for ptid in sorted(rows):
        fields = {k: v[1] for k, v in rows[ptid].items() if keep(k)}
        if not fields:
            continue
        sets = ", ".join(f"{k} = {number(v)}" for k, v in sorted(fields.items()))
        lines.append(f"UPDATE master_part_research SET {sets} WHERE ptid = '{ptid}';")
        count += len(fields)
    (args.out / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return count


source = profile.get("source", "the online game's parameters")
args.out.mkdir(parents=True, exist_ok=True)
materials = write("materials.sql", lambda k: k not in SPLITHIUM, [
    "Research material counts as the online game had them: what crafting and each",
    "upgrade take of each material. Recorded by S3er0i9ng from " + source + ".",
    "Generated by tools/build_online_research_costs.py - do not edit by hand.",
])
splithium = write("splithium.sql", lambda k: k in SPLITHIUM, [
    "Research SPLithium costs as the online game had them, for crafting and upgrades.",
    "Recorded by S3er0i9ng from " + source + ".",
    "Generated by tools/build_online_research_costs.py - do not edit by hand.",
])
print(f"checked against {args.vanilla} ({version[0] if version else 'unknown version'}): "
      f"all {sum(len(f) for f in rows.values()):,} offline values match")
print(f"wrote {args.out}: materials.sql ({materials:,} values), splithium.sql ({splithium:,} values) "
      f"over {len(rows):,} recipes")
